import { useEffect, useId, useMemo, useRef, useState } from 'react'
import { Link } from 'react-router-dom'
import QRCode from 'qrcode'
import type { Payment } from '../../api/paymentsApi'
import { localDemoPaymentApi, type LocalDemoConfirmResult } from '../../api/localDemoPaymentApi'
import {
  formatPaymentMoney,
  PAYMENT_PATHS,
  paymentStatusToneCode,
} from '../../pages/member/paymentsModel'
import { Button, Card, Notice, StatusBadge } from '../ui'
import { buttonClassName } from '../ui/buttonClassName'
import { demoQrImageUrl, demoQrSyntheticPayload } from './demoQr'
import { demoPaymentAmountAvailable, demoReference } from './demoDetails'
import './demoQr.css'

export interface DemoQrCardProps {
  payment: Pick<Payment, 'id' | 'amount'> & { code?: string; status?: string }
  onSettled?: () => void
}

/**
 * Minimal presentation-ready QR demo card.
 * Displays exactly one QR image generated by QRServer (with offline SVG fallback),
 * server-authoritative payment reference and amount, and exactly one confirmation button.
 */
export function DemoQrCard({ payment, onSettled }: DemoQrCardProps) {
  return (
    <DemoQrCardContent
      key={`${payment.id}:${payment.amount}`}
      payment={payment}
      onSettled={onSettled}
    />
  )
}

function DemoQrCardContent({ payment, onSettled }: DemoQrCardProps) {
  const titleId = useId()
  const descriptionId = useId()
  const [capability, setCapability] = useState<boolean | null>(null)
  const [useFallback, setUseFallback] = useState(false)
  const [isSubmitting, setIsSubmitting] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [settledResult, setSettledResult] = useState<LocalDemoConfirmResult | null>(null)
  const mounted = useRef(false)

  useEffect(() => {
    mounted.current = true
    const controller = new AbortController()

    localDemoPaymentApi
      .capability(controller.signal)
      .then((enabled) => {
        if (mounted.current) {
          setCapability(enabled)
        }
      })
      .catch(() => {
        if (mounted.current) {
          setCapability(false)
        }
      })

    return () => {
      mounted.current = false
      controller.abort()
    }
  }, [payment.id])

  const reference = payment.code ?? demoReference(payment.id)
  const amountValid = demoPaymentAmountAvailable(payment.amount)

  const syntheticPayload = useMemo(() => {
    try {
      if (!amountValid) return null
      return demoQrSyntheticPayload(payment.id, payment.code)
    } catch {
      return null
    }
  }, [payment.id, payment.code, amountValid])

  const qrImageUrl = useMemo(() => {
    if (!syntheticPayload) return null
    return demoQrImageUrl(syntheticPayload, 240)
  }, [syntheticPayload])

  const fallbackSvg = useMemo(() => {
    if (!syntheticPayload) return null
    try {
      const qr = QRCode.create(syntheticPayload, { errorCorrectionLevel: 'M' })
      const quietZone = 4
      const size = qr.modules.size + quietZone * 2
      const path = Array.from(qr.modules.data, (dark, index) =>
        dark
          ? `M${(index % qr.modules.size) + quietZone} ${
              Math.floor(index / qr.modules.size) + quietZone
            }h1v1h-1z`
          : ''
      ).join('')
      return { size, path }
    } catch {
      return null
    }
  }, [syntheticPayload])

  async function handleConfirm() {
    if (isSubmitting || settledResult !== null || capability !== true) {
      return
    }
    setIsSubmitting(true)
    setError(null)
    try {
      const result = await localDemoPaymentApi.confirm(payment.id)
      if (mounted.current) {
        setSettledResult(result)
      }
    } catch (err: unknown) {
      if (mounted.current) {
        const msg =
          err instanceof Error
            ? err.message
            : 'Confirmation failed. Please refresh and check authoritative payment status.'
        setError(msg)
      }
    } finally {
      if (mounted.current) {
        setIsSubmitting(false)
      }
    }
  }

  if (!amountValid || !syntheticPayload) {
    return (
      <Card title="Simulated QR Payment" className="qr-demo-card" aria-label="Non-payable QR demo">
        <Notice tone="danger">
          The demo QR could not be generated. No payment was made. Choose another payment or reopen
          this demo.
        </Notice>
      </Card>
    )
  }

  return (
    <Card title="Simulated QR Payment" className="qr-demo-card" aria-label="Non-payable QR demo">
      <p className="notice notice--warning">Simulated QR Payment - Demo only - No real money transferred.</p>
      <p className="card__intro">
        Scan with your phone camera to view the synthetic demo reference text. This is an external
        presentation QR and cannot transfer money.
      </p>

      {capability === false && (
        <Notice tone="danger">
          Simulation is unavailable in local demo mode. Make sure the backend local-demo profile and
          PAYMENT_LOCAL_DEMO_ENABLED are active.
        </Notice>
      )}

      <div className="qr-demo-card__body">
        <figure className="qr-demo-card__figure">
          {!useFallback && qrImageUrl ? (
            <img
              src={qrImageUrl}
              alt={`Non-payable demo QR for payment ${payment.id}`}
              className="qr-demo-card__image"
              referrerPolicy="no-referrer"
              width={240}
              height={240}
              onError={() => setUseFallback(true)}
            />
          ) : fallbackSvg ? (
            <svg
              className="qr-demo-card__symbol"
              viewBox={`0 0 ${fallbackSvg.size} ${fallbackSvg.size}`}
              role="img"
              aria-labelledby={`${titleId} ${descriptionId}`}
              shapeRendering="crispEdges"
            >
              <title id={titleId}>Non-payable demo QR for payment {payment.id}</title>
              <desc id={descriptionId}>
                Encodes synthetic non-payable reference. No banking instruction or payment URL is encoded.
              </desc>
              <rect width={fallbackSvg.size} height={fallbackSvg.size} className="qr-demo-card__paper" />
              <path d={fallbackSvg.path} fill="currentColor" />
            </svg>
          ) : (
            <p>QR code unavailable</p>
          )}
          <figcaption>Simulated QR - No real bank transfer</figcaption>
        </figure>

        <dl className="summary-list">
          <div>
            <dt>Payment reference</dt>
            <dd>{reference}</dd>
          </div>
          <div>
            <dt>Amount from payment</dt>
            <dd>{formatPaymentMoney(payment.amount)}</dd>
          </div>
          <div>
            <dt>Status</dt>
            <dd>
              <StatusBadge
                status={paymentStatusToneCode(settledResult ? 'SUCCESS' : payment.status ?? 'PENDING')}
                label={settledResult ? 'Paid - Simulated' : payment.status ?? 'Pending'}
              />
            </dd>
          </div>
          <div>
            <dt>Settlement type</dt>
            <dd>SIMULATED (No real money transferred)</dd>
          </div>
        </dl>
      </div>

      <div className="qr-demo-entry">
        {settledResult ? (
          <div>
            <Notice tone="success" live="off">
              Paid - Simulated. Payment successfully confirmed via Sportify QR Simulator.
            </Notice>
            <div style={{ marginTop: 'var(--space-4)' }}>
              <Link
                className={buttonClassName('secondary', 'md')}
                to={
                  settledResult.invoiceId
                    ? PAYMENT_PATHS.receipt(settledResult.invoiceId)
                    : PAYMENT_PATHS.summary(payment.id)
                }
              >
                View payment receipt
              </Link>
            </div>
          </div>
        ) : (
          <Button
            variant="primary"
            disabled={capability !== true || isSubmitting}
            onClick={() => void handleConfirm()}
          >
            {isSubmitting ? 'Confirming simulated payment...' : 'Simulate Payment Confirmation'}
          </Button>
        )}
      </div>

      <div role="status" aria-live="polite" aria-atomic="true">
        {isSubmitting && (
          <Notice tone="info" live="off">
            Confirming simulated payment...
          </Notice>
        )}
      </div>

      <div role="alert" aria-atomic="true">
        {error && (
          <Notice tone="danger" live="off">
            {error}
          </Notice>
        )}
      </div>
    </Card>
  )
}
