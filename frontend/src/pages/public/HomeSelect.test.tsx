import { render, screen } from '@testing-library/react'
import type { FormEvent } from 'react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { HomeSelect } from './HomeSelect'

describe('Home Sports filter', () => {
  it('retains keyboard selection, reset, selected announcement, Escape and focus', async () => {
    const onChange = vi.fn()
    const user = userEvent.setup()
    render(<HomeSelect sports label="Sport" placeholder="All sports" value="2" options={[{ value: '1', label: 'Football' }, { value: '2', label: 'Tennis' }]} onChange={onChange} />)
    const trigger = screen.getByRole('button', { name: 'Sport Tennis' })
    await user.click(trigger)
    expect(screen.getByRole('option', { name: 'Tennis' })).toHaveAttribute('aria-selected', 'true')
    expect(screen.getByRole('listbox')).toHaveClass('home-select__list--sports')
    await user.keyboard('{Home}{Enter}')
    expect(onChange).toHaveBeenLastCalledWith('')
    expect(trigger).toHaveFocus()
    await user.keyboard('{ArrowDown}{Home}{ArrowDown}{Enter}')
    expect(onChange).toHaveBeenLastCalledWith('1')
    await user.click(trigger)
    await user.keyboard('{Escape}')
    expect(trigger).toHaveFocus()
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
  })

  it.each([7, 31])('moves one vertical option without wrapping with %i options', async (count) => {
    const onChange = vi.fn()
    const submit = vi.fn((event: FormEvent) => event.preventDefault())
    const user = userEvent.setup()
    render(<form onSubmit={submit}><HomeSelect sports label="Sport" placeholder="All sports" value="" options={Array.from({ length: count - 1 }, (_, i) => ({ value: String(i + 1), label: `Sport ${i + 1}` }))} onChange={onChange} /></form>)
    await user.click(screen.getByRole('button', { name: 'Sport All sports' }))
    const list = screen.getByRole('listbox')
    const options = screen.getAllByRole('option')
    const active = (index: number) => expect(list).toHaveAttribute('aria-activedescendant', options[index].id)
    expect(list).toHaveAccessibleDescription(/One column.*without wrapping/)
    active(0)
    await user.keyboard('{ArrowUp}{ArrowLeft}')
    active(0)
    await user.keyboard('{ArrowRight}')
    active(0)
    await user.keyboard('{ArrowDown}')
    active(1)
    await user.keyboard('{ArrowLeft}{ArrowRight}')
    active(1)
    await user.keyboard('{ArrowUp}')
    active(0)
    await user.keyboard('{End}')
    active(count - 1)
    await user.keyboard('{ArrowDown}{ArrowRight}{ArrowLeft}')
    active(count - 1)
    await user.keyboard('{ArrowUp}{ArrowRight}{ArrowLeft}')
    active(count - 2)
    await user.keyboard('{ArrowDown}')
    active(count - 1)
    expect(options[0]).toHaveAttribute('aria-selected', 'true')
    expect(onChange).not.toHaveBeenCalled()
    await user.keyboard('{Home}{ArrowDown}{Enter}')
    expect(onChange).toHaveBeenCalledWith('1')
    expect(submit).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: 'Sport All sports' })).toHaveFocus()
  })

  it.each(['Level', 'Training'])('preserves the %s one-column keyboard policy', async (label) => {
    const user = userEvent.setup()
    const onChange = vi.fn()
    render(<HomeSelect label={label} placeholder="All" value="" options={[{ value: '1', label: 'First' }, { value: '2', label: 'Last' }]} onChange={onChange} />)
    await user.click(screen.getByRole('button', { name: `${label} All` }))
    const list = screen.getByRole('listbox')
    const options = screen.getAllByRole('option')
    await user.keyboard('{ArrowDown}{ArrowRight}{ArrowLeft}')
    expect(list).toHaveAttribute('aria-activedescendant', options[1].id)
    await user.keyboard('{ArrowDown}{ArrowDown}')
    expect(list).toHaveAttribute('aria-activedescendant', options[2].id)
    await user.keyboard('{Home}{ArrowUp}{End}{Enter}')
    expect(onChange).toHaveBeenCalledWith('2')
  })

  it('clamps the active option when a refreshed catalogue shrinks', async () => {
    const user = userEvent.setup()
    const onChange = vi.fn()
    const props = { sports: true, label: 'Sport', placeholder: 'All sports', value: '', onChange }
    const { rerender } = render(<HomeSelect {...props} options={Array.from({ length: 30 }, (_, i) => ({ value: String(i + 1), label: `Sport ${i + 1}` }))} />)
    await user.click(screen.getByRole('button', { name: 'Sport All sports' }))
    await user.keyboard('{End}')
    rerender(<HomeSelect {...props} options={[{ value: '1', label: 'Football' }, { value: '2', label: 'Tennis' }]} />)
    expect(screen.getByRole('listbox')).toHaveAttribute('aria-activedescendant', screen.getByRole('option', { name: 'Tennis' }).id)
    await user.keyboard('{Enter}')
    expect(onChange).toHaveBeenCalledWith('2')
  })

  it('keeps future options reachable and closes when focus leaves', async () => {
    const onChange = vi.fn()
    const user = userEvent.setup()
    render(<><HomeSelect sports label="Sport" placeholder="All sports" value="" options={Array.from({ length: 30 }, (_, i) => ({ value: String(i + 1), label: `Sport ${i + 1}` }))} onChange={onChange} /><button>Next filter</button></>)
    await user.click(screen.getByRole('button', { name: 'Sport All sports' }))
    expect(screen.getAllByRole('option')).toHaveLength(31)
    await user.keyboard('{End}{Enter}')
    expect(onChange).toHaveBeenCalledWith('30')
    await user.click(screen.getByRole('button', { name: 'Sport All sports' }))
    await user.tab()
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Next filter' })).toHaveFocus()
  })
})
